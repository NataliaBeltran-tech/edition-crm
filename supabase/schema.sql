-- Próximo lead de WhatsApp para la cuenta activa (asignados primero) y cuántos quedan
create or replace function public.crm_next_wa(p_account bigint, p_import bigint default null, p_exclude bigint[] default '{}') returns jsonb
language sql stable security invoker set search_path = public as $$
  with base as (
    select c.* from contacts c
    where c.user_id = auth.uid() and c.stage = 'por_contactar' and c.greeting_at is null and coalesce(c.has_wa, 1) <> 0
      and (c.account_id = p_account or c.account_id is null)
      and (p_import is null or c.import_id = p_import)
  )
  select jsonb_build_object(
    'remaining', (select count(*) from base),
    'lead', (select to_jsonb(b) || jsonb_build_object('import_name', (select name from imports i where i.id = b.import_id))
             from base b where not (b.id = any(coalesce(p_exclude, '{}'))) order by (b.account_id is null), b.id limit 1))
$$;

-- Próximo lead de Instagram
create or replace function public.crm_next_ig(p_account bigint, p_import bigint default null, p_exclude bigint[] default '{}') returns jsonb
language sql stable security invoker set search_path = public as $$
  with base as (
    select l.* from ig_leads l
    where l.user_id = auth.uid() and l.status = 'nuevo' and (l.account_id = p_account or l.account_id is null)
      and (p_import is null or l.import_id = p_import)
  )
  select jsonb_build_object(
    'remaining', (select count(*) from base),
    'lead', (select to_jsonb(b) || jsonb_build_object('import_name', (select name from imports i where i.id = b.import_id))
             from base b where not (b.id = any(coalesce(p_exclude, '{}'))) order by (b.account_id is null), b.id limit 1))
$$;

grant execute on function public.crm_next_wa, public.crm_next_ig to authenticated;
revoke execute on function public.crm_next_wa, public.crm_next_ig from anon, public;

-- ---------- Integridad entre usuarios: no se puede apuntar a filas de otra persona ----------
create or replace function public.crm_check_refs() returns trigger
language plpgsql security invoker set search_path = public as $$
begin
  if auth.uid() is null then return new; end if;  -- editor SQL / administración
  if tg_table_name = 'contacts' then
    if new.account_id is not null and not exists (select 1 from accounts where id = new.account_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
    if new.import_id is not null and not exists (select 1 from imports where id = new.import_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
  elsif tg_table_name = 'messages' then
    if not exists (select 1 from contacts where id = new.contact_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
    if new.account_id is not null and not exists (select 1 from accounts where id = new.account_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
  elsif tg_table_name = 'ig_leads' then
    if new.account_id is not null and not exists (select 1 from ig_accounts where id = new.account_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
    if new.import_id is not null and not exists (select 1 from imports where id = new.import_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
  elsif tg_table_name = 'ig_contact_log' then
    if new.lead_id is not null and not exists (select 1 from ig_leads where id = new.lead_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
    if new.account_id is not null and not exists (select 1 from ig_accounts where id = new.account_id and user_id = auth.uid()) then raise exception 'Referencia no válida'; end if;
  end if;
  return new;
end $$;
do $$
declare t text;
begin
  foreach t in array array['contacts','messages','ig_leads','ig_contact_log'] loop
    if not exists (select 1 from pg_trigger where tgname = 'crm_check_refs' and tgrelid = ('public.' || t)::regclass) then
      execute format('create trigger crm_check_refs before insert or update on public.%I for each row execute function public.crm_check_refs()', t);
    end if;
  end loop;
end $$;

-- ---------- Registrar envíos en un solo paso (todo o nada) ----------
-- Primer mensaje de WhatsApp: valida etapa y cupo, guarda el mensaje, pasa a "Contactado" y fija la pausa.
create or replace function public.crm_register_greeting(p_contact bigint, p_account bigint, p_body text, p_template bigint, p_day_start bigint, p_next_ts bigint)
returns jsonb language plpgsql security invoker set search_path = public as $$
declare c contacts%rowtype; v_limit int; v_sent int; t bigint := public.now_ms();
begin
  if auth.uid() is null then raise exception 'Sin sesión'; end if;
  if coalesce(trim(p_body), '') = '' then raise exception 'El mensaje está vacío.'; end if;
  select daily_limit into v_limit from accounts where id = p_account and user_id = auth.uid();
  if v_limit is null then raise exception 'Cuenta no encontrada.'; end if;
  select * into c from contacts where id = p_contact and user_id = auth.uid() for update;
  if c.id is null then raise exception 'No encontré ese contacto.'; end if;
  if c.stage <> 'por_contactar' or c.greeting_at is not null then raise exception 'A este contacto ya le escribiste.'; end if;
  select count(*) into v_sent from messages where user_id = auth.uid() and account_id = p_account and direction = 'out' and kind = 'saludo' and ts >= p_day_start;
  if v_sent >= v_limit then raise exception 'Esta cuenta ya llegó a su cupo de hoy.'; end if;
  insert into messages(contact_id, account_id, direction, kind, template_id, body, ts) values (p_contact, p_account, 'out', 'saludo', p_template, trim(p_body), t);
  update contacts set stage = 'contactado', stage_changed_at = t, fu_count = 0, snooze_until = null, greeting_at = coalesce(greeting_at, t),
    account_id = p_account, greeting_template_id = p_template, last_out_at = t, has_wa = 1 where id = p_contact;
  insert into settings(key, value) values ('wa_next_' || p_account, p_next_ts::text)
    on conflict (user_id, key) do update set value = excluded.value;
  return jsonb_build_object('sent', v_sent + 1, 'limit', v_limit);
end $$;

-- Instagram: primer mensaje o seguimiento registrado
create or replace function public.crm_ig_contacted(p_lead bigint, p_account bigint, p_kind text, p_day_start bigint) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare l ig_leads%rowtype; v_limit int; v_sent int; t bigint := public.now_ms();
begin
  if auth.uid() is null then raise exception 'Sin sesión'; end if;
  select daily_limit into v_limit from ig_accounts where id = p_account and user_id = auth.uid();
  if v_limit is null then raise exception 'Cuenta no encontrada.'; end if;
  select * into l from ig_leads where id = p_lead and user_id = auth.uid() for update;
  if l.id is null then raise exception 'No encontré ese lead.'; end if;
  if p_kind = 'first' then
    if l.status <> 'nuevo' then raise exception 'Este lead ya fue contactado.'; end if;
    select count(*) into v_sent from ig_contact_log where user_id = auth.uid() and account_id = p_account and kind = 'first' and ts >= p_day_start;
    if v_sent >= v_limit then raise exception 'Esta cuenta ya llegó a su cupo de hoy.'; end if;
    insert into ig_contact_log(lead_id, account_id, kind, ts) values (p_lead, p_account, 'first', t);
    update ig_leads set status = 'contactado', status_changed_at = t, account_id = p_account, fu_count = 0,
      first_contact_at = coalesce(first_contact_at, t), last_contact_at = t where id = p_lead;
  else
    if l.status <> 'contactado' then raise exception 'Este seguimiento ya se registró.'; end if;
    insert into ig_contact_log(lead_id, account_id, kind, ts) values (p_lead, p_account, 'followup', t);
    update ig_leads set fu_count = fu_count + 1, last_contact_at = t, account_id = coalesce(account_id, p_account), snooze_until = null where id = p_lead;
  end if;
  select count(*) into v_sent from ig_contact_log where user_id = auth.uid() and account_id = p_account and kind = 'first' and ts >= p_day_start;
  return jsonb_build_object('sent', v_sent, 'limit', v_limit);
end $$;

-- Último mensaje de cada conversación
create or replace function public.crm_last_messages() returns table(contact_id bigint, body text, direction text, ts bigint)
language sql stable security invoker set search_path = public as $$
  select distinct on (m.contact_id) m.contact_id, m.body, m.direction, m.ts
  from messages m where m.user_id = auth.uid() order by m.contact_id, m.ts desc
$$;

grant execute on function public.crm_register_greeting, public.crm_ig_contacted, public.crm_last_messages to authenticated;
revoke execute on function public.crm_register_greeting, public.crm_ig_contacted, public.crm_last_messages, public.crm_check_refs from anon, public;
