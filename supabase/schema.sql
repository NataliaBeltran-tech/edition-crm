create or replace function public.now_ms() returns bigint
language sql stable as $$ select (extract(epoch from clock_timestamp()) * 1000)::bigint $$;

-- ---------- Tablas ----------
create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  phone text,
  daily_limit int not null default 15,
  active boolean not null default true,
  created_at bigint not null default public.now_ms()
);

create table if not exists public.imports (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  channel text not null check (channel in ('whatsapp', 'instagram')),
  name text, filename text, rubro text default '',
  total int not null default 0, added int not null default 0, duplicated int not null default 0, invalid int not null default 0,
  market text not null default 'co_mx', country text,
  created_at bigint not null default public.now_ms()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  phone text not null,
  name text default '', company text default '', rubro text default '', city text default '',
  stage text not null default 'por_contactar',
  account_id bigint references public.accounts(id) on delete set null,
  import_id bigint references public.imports(id) on delete set null,
  tags jsonb not null default '[]', notes text default '', has_wa smallint, meeting_at bigint,
  greeting_template_id bigint,
  greeting_at bigint, replied_at bigint, pitch_at bigint, interested_at bigint, meeting_set_at bigint, won_at bigint,
  last_in_at bigint, last_out_at bigint, fu_count int not null default 0, snooze_until bigint, unread int not null default 0,
  stage_changed_at bigint, extra jsonb not null default '{}', reason text, market text not null default 'co_mx',
  created_at bigint not null default public.now_ms(),
  unique (user_id, phone)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  contact_id bigint not null references public.contacts(id) on delete cascade,
