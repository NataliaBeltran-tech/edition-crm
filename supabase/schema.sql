  import_id bigint references public.imports(id) on delete set null,
  account_id bigint references public.ig_accounts(id) on delete set null,
  status text not null default 'nuevo', reason text, notes text default '', meeting_at bigint,
  fu_count int not null default 0, first_contact_at bigint, last_contact_at bigint, replied_at bigint,
