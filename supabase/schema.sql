-- ---------- Seguridad: cada usuario solo ve sus filas ----------
do $$
declare t text;
begin
  foreach t in array array['accounts','imports','contacts','messages','templates','ig_accounts','ig_leads','ig_contact_log','settings'] loop
    execute format('alter table public.%I enable row level security', t);
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'solo_mis_datos') then
      execute format('create policy solo_mis_datos on public.%I for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid())', t);
    end if;
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- ---------- Funciones (corren con los permisos del usuario: respetan RLS) ----------

-- Cuántos leads pendientes tiene cada cuenta (para repartir parejo)
create or replace function public.crm_pending(p_channel text, p_account bigint) returns int
language sql stable security invoker set search_path = public as $$
  select case when p_channel = 'whatsapp' then
    (select count(*)::int from contacts where user_id = auth.uid() and account_id = p_account and stage = 'por_contactar'
       and greeting_at is null and coalesce(has_wa, 1) <> 0)
  else
    (select count(*)::int from ig_leads where user_id = auth.uid() and account_id = p_account and status = 'nuevo')
  end
$$;

-- Asigna cada lead a la cuenta con menos pendientes
create or replace function public.crm_assign(p_channel text, p_ids bigint[], p_accounts bigint[]) returns void
language plpgsql security invoker set search_path = public as $$
declare
  counts int[] := '{}';
  i int; best int; lead bigint;
begin
  -- solo cuentas propias
  if p_channel = 'whatsapp' then
    select coalesce(array_agg(id order by id), '{}') into p_accounts from accounts where user_id = auth.uid() and id = any(coalesce(p_accounts, '{}'));
  else
    select coalesce(array_agg(id order by id), '{}') into p_accounts from ig_accounts where user_id = auth.uid() and id = any(coalesce(p_accounts, '{}'));
  end if;
  if array_length(p_accounts, 1) is null or p_ids is null then return; end if;
  for i in 1 .. array_length(p_accounts, 1) loop counts := counts || public.crm_pending(p_channel, p_accounts[i]); end loop;
  foreach lead in array p_ids loop
    best := 1;
    for i in 2 .. array_length(p_accounts, 1) loop if counts[i] < counts[best] then best := i; end if; end loop;
    if p_channel = 'whatsapp' then update contacts set account_id = p_accounts[best] where id = lead and user_id = auth.uid();
    else update ig_leads set account_id = p_accounts[best] where id = lead and user_id = auth.uid(); end if;
    counts[best] := counts[best] + 1;
  end loop;
end $$;

-- Importar una lista. Las filas llegan ya validadas y sin repetidos dentro del archivo.
-- p_meta: {name, filename, rubro, market, country, total, dup_file, invalid, account_ids: []}
create or replace function public.crm_import(p_channel text, p_meta jsonb, p_rows jsonb, p_dry boolean default false) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare
  v_import bigint; v_dup int; v_added int := 0; v_ids bigint[] := '{}'; v_id bigint; r jsonb; v_accounts bigint[];
begin
  if auth.uid() is null then raise exception 'Sin sesión'; end if;
  if p_channel = 'whatsapp' then
    select count(*) into v_dup from jsonb_array_elements(p_rows) x
      where exists (select 1 from contacts c where c.user_id = auth.uid() and c.phone = x->>'phone');
  else
    select count(*) into v_dup from jsonb_array_elements(p_rows) x
      where exists (select 1 from ig_leads l where l.user_id = auth.uid() and l.username = x->>'username');
  end if;
  if p_dry then return jsonb_build_object('dup_db', v_dup, 'valid', jsonb_array_length(p_rows) - v_dup); end if;

  insert into imports(channel, name, filename, rubro, total, added, duplicated, invalid, market, country)
  values (p_channel, coalesce(nullif(p_meta->>'name', ''), p_meta->>'filename', 'Lista'), p_meta->>'filename', coalesce(p_meta->>'rubro', ''),
          coalesce((p_meta->>'total')::int, 0), 0, coalesce((p_meta->>'dup_file')::int, 0) + v_dup, coalesce((p_meta->>'invalid')::int, 0),
          coalesce(p_meta->>'market', 'co_mx'), p_meta->>'country')
  returning id into v_import;

  for r in select * from jsonb_array_elements(p_rows) loop
    v_id := null;
    if p_channel = 'whatsapp' then
      insert into contacts(phone, name, company, rubro, city, import_id, extra, market)
      values (r->>'phone', coalesce(r->>'name', ''), coalesce(r->>'company', ''), coalesce(nullif(r->>'rubro', ''), p_meta->>'rubro', ''),
              coalesce(r->>'city', ''), v_import, coalesce(r->'extra', '{}'::jsonb), coalesce(p_meta->>'market', 'co_mx'))
      on conflict (user_id, phone) do nothing returning id into v_id;
    else
      insert into ig_leads(username, link, name, rubro, import_id, extra, market, followers)
      values (r->>'username', 'https://www.instagram.com/' || (r->>'username') || '/', coalesce(r->>'name', ''),
              coalesce(nullif(r->>'rubro', ''), p_meta->>'rubro', ''), v_import, coalesce(r->'extra', '{}'::jsonb),
              coalesce(p_meta->>'market', 'co_mx'), nullif(r->>'followers', '')::int)
      on conflict (user_id, username) do nothing returning id into v_id;
    end if;
    if v_id is not null then v_ids := v_ids || v_id; v_added := v_added + 1; end if;
  end loop;

  update imports set added = v_added where id = v_import;
  select coalesce(array_agg(x::bigint), '{}') into v_accounts from jsonb_array_elements_text(coalesce(p_meta->'account_ids', '[]'::jsonb)) x;
  perform public.crm_assign(p_channel, v_ids, v_accounts);
  return jsonb_build_object('import_id', v_import, 'added', v_added, 'dup_db', v_dup);
end $$;

-- Re-repartir los pendientes de una lista
create or replace function public.crm_distribute(p_import bigint, p_accounts bigint[]) returns int
language plpgsql security invoker set search_path = public as $$
declare v_channel text; v_ids bigint[];
begin
  select channel into v_channel from imports where id = p_import and user_id = auth.uid();
  if v_channel is null then raise exception 'Lista no encontrada'; end if;
  if v_channel = 'whatsapp' then
    select coalesce(array_agg(id order by id), '{}') into v_ids from contacts
      where user_id = auth.uid() and import_id = p_import and stage = 'por_contactar' and greeting_at is null and coalesce(has_wa, 1) <> 0;
    update contacts set account_id = null where id = any(v_ids);
  else
    select coalesce(array_agg(id order by id), '{}') into v_ids from ig_leads
      where user_id = auth.uid() and import_id = p_import and status = 'nuevo';
    update ig_leads set account_id = null where id = any(v_ids);
  end if;
  perform public.crm_assign(v_channel, v_ids, p_accounts);
  return coalesce(array_length(v_ids, 1), 0);
end $$;

-- Borrar una lista: solo se borran los leads nunca contactados; el resto queda sin lista.
create or replace function public.crm_delete_import(p_import bigint) returns int
language plpgsql security invoker set search_path = public as $$
declare v_channel text; v_deleted int;
begin
  select channel into v_channel from imports where id = p_import and user_id = auth.uid();
  if v_channel is null then raise exception 'Lista no encontrada'; end if;
  if v_channel = 'whatsapp' then
    delete from contacts c where c.user_id = auth.uid() and c.import_id = p_import and c.stage = 'por_contactar'
      and c.greeting_at is null and not exists (select 1 from messages m where m.contact_id = c.id);
  else
    delete from ig_leads l where l.user_id = auth.uid() and l.import_id = p_import and l.status = 'nuevo' and l.first_contact_at is null;
  end if;
  get diagnostics v_deleted = row_count;
  delete from imports where id = p_import and user_id = auth.uid(); -- el resto queda con import_id = null
  return v_deleted;
end $$;

-- Estadísticas de las listas
create or replace function public.crm_import_stats(p_channel text) returns jsonb
language sql stable security invoker set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(i) || s.stats order by i.created_at desc), '[]'::jsonb)
  from imports i
  cross join lateral (
    select case when p_channel = 'whatsapp' then (
      select jsonb_build_object(
        'por_contactar', count(*) filter (where stage = 'por_contactar' and greeting_at is null and coalesce(has_wa,1) <> 0),
        'contactados', count(*) filter (where greeting_at is not null),
        'respondieron', count(*) filter (where greeting_at is not null and replied_at is not null))
      from contacts where import_id = i.id and user_id = auth.uid())
    else (
      select jsonb_build_object(
        'por_contactar', count(*) filter (where status = 'nuevo'),
        'contactados', count(*) filter (where first_contact_at is not null),
        'respondieron', count(*) filter (where replied_at is not null))
      from ig_leads where import_id = i.id and user_id = auth.uid())
    end as stats
  ) s
  where i.user_id = auth.uid() and i.channel = p_channel
$$;

-- Métricas (embudo por hitos)
create or replace function public.crm_metrics() returns jsonb
language sql stable security invoker set search_path = public as $$
  with c as (select * from contacts where user_id = auth.uid()),
  f as (
    select account_id, coalesce(nullif(trim(rubro), ''), 'Sin rubro') rubro, greeting_template_id,
      greeting_at is not null contactado, (greeting_at is not null and replied_at is not null) respondio,
      pitch_at is not null pitch, interested_at is not null interesado, meeting_set_at is not null reunion,
      won_at is not null ganado, stage = 'no_interesado' no_int, has_wa = 0 sin_wa
    from c
  ),
  l as (select * from ig_leads where user_id = auth.uid())
  select jsonb_build_object(
    'funnel', (select jsonb_build_object('contactados', count(*) filter (where contactado), 'respondieron', count(*) filter (where respondio),
        'pitch', count(*) filter (where pitch), 'interesados', count(*) filter (where interesado), 'reuniones', count(*) filter (where reunion),
        'ganados', count(*) filter (where ganado), 'no_interesados', count(*) filter (where no_int), 'sin_whatsapp', count(*) filter (where sin_wa)) from f),
    'byAccount', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name,
        'contactados', (select count(*) from f where f.account_id = a.id and contactado),
        'respondieron', (select count(*) from f where f.account_id = a.id and respondio),
        'interesados', (select count(*) from f where f.account_id = a.id and interesado),
        'reuniones', (select count(*) from f where f.account_id = a.id and reunion)) order by a.id)
      from accounts a where a.user_id = auth.uid()), '[]'::jsonb),
    'byRubro', coalesce((select jsonb_agg(x) from (select rubro, count(*) filter (where contactado) contactados, count(*) filter (where respondio) respondieron,
        count(*) filter (where interesado) interesados, count(*) filter (where reunion) reuniones from f group by rubro
        having count(*) filter (where contactado) > 0 order by 2 desc) x), '[]'::jsonb),
    'byTemplate', coalesce((select jsonb_agg(x) from (select t.id, t.name, t.market, count(*) contactados, count(*) filter (where respondio) respondieron,
        count(*) filter (where interesado) interesados, count(*) filter (where reunion) reuniones
        from f join templates t on t.id = f.greeting_template_id where contactado group by t.id, t.name, t.market order by 4 desc) x), '[]'::jsonb),
    'ig', jsonb_build_object(
      'funnel', (select jsonb_build_object('contactados', count(*) filter (where first_contact_at is not null),
          'respondieron', count(*) filter (where first_contact_at is not null and replied_at is not null),
          'en_conversacion', count(*) filter (where status in ('en_conversacion','reunion','cerrado')),
          'reuniones', count(*) filter (where meeting_at is not null or status in ('reunion','cerrado')),
          'cerrados', count(*) filter (where status = 'cerrado'), 'descartados', count(*) filter (where status = 'descartado')) from l),
      'byAccount', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name, 'color', a.color,
          'contactados', (select count(*) from l where l.account_id = a.id and first_contact_at is not null),
          'respondieron', (select count(*) from l where l.account_id = a.id and first_contact_at is not null and replied_at is not null),
          'reuniones', (select count(*) from l where l.account_id = a.id and (meeting_at is not null or status in ('reunion','cerrado'))),
          'descartados', (select count(*) from l where l.account_id = a.id and status = 'descartado')) order by a.id)
        from ig_accounts a where a.user_id = auth.uid()), '[]'::jsonb))
  )
$$;

